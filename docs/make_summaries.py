"""Generate the repository's index pages from catalog.csv and every <folder>/scores.csv (standard library only).

Usage: python3 docs/make_summaries.py
Writes:
  docs/catalog.md          every folder by area: data, what it is scored against, tools, post, CI status
  docs/scores_summary.csv  all scores.csv rows in the standard columns
  docs/scores_summary.md   one section per folder with a scores.csv: its metrics by tool and setting
CI re-runs this script and fails if the committed pages differ, so they always match catalog.csv and the scores.
It also fails if a scores.csv breaks the standard header, has an empty value or names another folder.
"""
import csv
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
COLUMNS = ["folder", "dataset", "tool", "version", "setting", "subset", "metric", "value", "n"]
CI_LABEL = {"reproduce": "re-run and compared", "smoke": "run (output not compared)", "no": "not in CI"}
GENERATED = "Generated by `docs/make_summaries.py`; do not edit by hand."

catalog = list(csv.DictReader(open(ROOT / "catalog.csv", newline="")))
by_folder = {r["folder"]: r for r in catalog}


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def link(url):
    if "/issues/" in url:
        return f"[issue #{url.rsplit('/', 1)[1]}]({url}) (no post yet)"
    if "doi.org" in url:
        return f"[preprint]({url})"
    return f"[post]({url})"


# ---- docs/catalog.md
out = ["# Catalog", "", GENERATED, "",
       f"{len(catalog)} folders. The same information as a table: [`catalog.csv`](../catalog.csv). "
       "CI: whether `ci/reproduce.sh` re-runs the folder from files in the repository.", ""]
for area in sorted({r["area"] for r in catalog}):
    out += [f"## {area}", "", "| Folder | Data | Scored against | Tools | Post | CI |", "|---|---|---|---|---|---|"]
    for r in sorted((r for r in catalog if r["area"] == area), key=lambda r: r["folder"]):
        out.append(f"| [{r['folder']}](../{r['folder']}) | {cell(r['data'])} | {cell(r['truth'])} | {cell(r['tools'])} | "
                   f"{link(r['post'])} | {CI_LABEL.get(r['ci'], r['ci'])} |")
    out.append("")
(DOCS / "catalog.md").write_text("\n".join(out))

# ---- docs/scores_summary.csv and .md
files = sorted(p for p in ROOT.glob("*/scores.csv") if p.parent.name in by_folder)
rows, errors = [], []
for f in files:
    with open(f, newline="") as fh:
        rd = csv.DictReader(fh)
        if rd.fieldnames != COLUMNS:
            errors.append(f"{f.relative_to(ROOT)}: header must be {','.join(COLUMNS)}")
            continue
        for i, r in enumerate(rd, 2):
            if not r["value"].strip():
                errors.append(f"{f.relative_to(ROOT)}:{i}: empty value")
            if r["folder"] != f.parent.name:
                errors.append(f"{f.relative_to(ROOT)}:{i}: folder column '{r['folder']}' is not '{f.parent.name}'")
            rows.append(r)
if errors:
    sys.exit("\n".join(errors))

with open(DOCS / "scores_summary.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=COLUMNS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)

out = ["# Scores across folders", "", GENERATED, "",
       f"{len(rows)} rows from the {len(files)} folders that write a `scores.csv`. "
       "All rows in one table: [`scores_summary.csv`](scores_summary.csv). Folder index: [catalog](catalog.md).", ""]
for f in files:
    folder = f.parent.name
    c = by_folder[folder]
    fr = [r for r in rows if r["folder"] == folder]
    out += [f"## [{folder}](../{folder})", "",
            f"Area: {c['area']} · Scored against: {c['truth']} · {link(c['post'])}", ""]
    for dataset in OrderedDict.fromkeys(r["dataset"] for r in fr):
        dr = [r for r in fr if r["dataset"] == dataset]
        cols = list(OrderedDict.fromkeys((r["subset"], r["metric"]) for r in dr))
        keys = list(OrderedDict.fromkeys((r["tool"], r["setting"]) for r in dr))
        val = {(r["tool"], r["setting"], r["subset"], r["metric"]): r["value"] for r in dr}
        show_setting = len({s for _, s in keys}) > 1
        head = ["Tool"] + (["Setting"] if show_setting else []) + [f"{m} ({s})" for s, m in cols]
        out += [f"**{cell(dataset)}**", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
        for tool, setting in keys:
            cells = [tool] + ([setting] if show_setting else []) + [val.get((tool, setting, s, m), "") for s, m in cols]
            out.append("| " + " | ".join(cell(x) for x in cells) + " |")
        out.append("")
(DOCS / "scores_summary.md").write_text("\n".join(out))
print(f"wrote docs/catalog.md ({len(catalog)} folders), docs/scores_summary.csv ({len(rows)} rows), "
      f"docs/scores_summary.md ({len(files)} folders)")
